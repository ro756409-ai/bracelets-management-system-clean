/** اسم مطبّع → المحافظات اللي بيظهر تحتها. أكتر من واحدة = ملتبس. */
const INDEX: Map<string, Set<string>> = (() => {
  const m = new Map<string, Set<string>>();
  const put = (name: string, gov: string) => {
    const k = normalizeAr(name);
    if (!k) return;
    if (!m.has(k)) m.set(k, new Set());
    m.get(k)!.add(gov);
  };
  for (const g of GOVERNORATES) put(g, g);
  for (const [gov, cities] of Object.entries(CITIES)) for (const c of cities) put(c, gov);
  return m;
})();

/** كل الأسماء مرتّبة من الأطول للأقصر — «كفر الشيخ» قبل «الشيخ». */
const NAMES_BY_LENGTH = [...INDEX.keys()].sort((a, b) => b.length - a.length);

/** هل الاسم المطبّع موجود ككلمة كاملة (مش جزء من كلمة أطول)؟ */
function containsWord(haystack: string, needle: string): boolean {
  return ` ${haystack} `.includes(` ${needle} `);
}

export interface GovernorateMatch {
  /** اسم المحافظة الرسمي، أو "" لو مش مؤكد. */
  governorate: string;
  /** المدينة/المركز اللي اتطابق (لو اتطابق باسم مدينة مش باسم محافظة). */
  city: string;
  /** اتطابق أكتر من محافظة محتملة — سيبنا الحقل فاضي عن قصد. */
  ambiguous: boolean;
}

/**
 * يحدّد المحافظة من نص العنوان.
 *
 *   • اسم محافظة مذكور صراحة → هو المرجع (بيحسم أي التباس في أسماء المدن).
 *   • وإلا: أسماء المدن المطابقة. لو كلها بتأدّي لمحافظة واحدة → اتأكدنا.
 *   • مدينة اسمها تحت أكتر من محافظة، أو مدن من محافظات مختلفة → **فاضي** (`ambiguous`).
 *   • مفيش تطابق → فاضي. مفيش «أقرب نتيجة» ولا أول كلمة.
 */
export function resolveGovernorate(address: string): GovernorateMatch {
  const text = normalizeAr(address);
  const empty: GovernorateMatch = { governorate: "", city: "", ambiguous: false };
  if (!text) return empty;

  const govSet = new Set(GOVERNORATES.map(g => normalizeAr(g)));
  const officialOf = (n: string) => GOVERNORATES.find(g => normalizeAr(g) === n) ?? "";

  // **«محافظة X» الصريحة بتكسب كل شيء.**
  //
  // عنوان زي «محافظة السويس / الموشي تعاونيات البحر الاحمر عند مسجد الحرمين» فيه
  // اسمين محافظات: السويس (المقصودة) والبحر الأحمر (جزء من اسم شارع). من غير
  // الأولوية دي كان الأطول بيكسب والنتيجة غلط.
  const marked = address.match(/محافظ[ةه]\s*[:：]?\s*([^\n،,]+)/);
  if (marked) {
    const t = normalizeAr(marked[1]);
    // بنجرّب الأسماء من الأطول للأقصر جوه النص اللي بعد «محافظة» مباشرة.
    for (const name of NAMES_BY_LENGTH) {
      if (!govSet.has(name)) continue;
      if (t === name || t.startsWith(`${name} `)) {
        const gov = officialOf(name);
        const rest = normalizeAr(address);
        const city = NAMES_BY_LENGTH.find(
          n => n !== name && containsWord(rest, n) && INDEX.get(n)!.has(gov)
        );
        return { governorate: gov, city: city ? denormalize(city, gov) : "", ambiguous: false };
      }
    }
    // «محافظة» مكتوبة بس الاسم مش في القايمة → فاضي، مش تخمين من باقي العنوان.
    return empty;
  }
  const hits: { name: string; govs: string[] }[] = [];
  for (const name of NAMES_BY_LENGTH) {
    if (!containsWord(text, name)) continue;
    // اسم أقصر جوه اسم أطول اتطابق قبله (مثل «الشيخ» جوه «كفر الشيخ») بيتتخطّى.
    if (hits.some(h => h.name.includes(name))) continue;
    hits.push({ name, govs: [...INDEX.get(name)!] });
  }
  if (hits.length === 0) return empty;

  // اسم محافظة واحد بس مذكور (بلا كلمة «محافظة») → هو المرجع.
  const govHits = hits.filter(h => govSet.has(h.name));
  if (govHits.length === 1) {
    const gov = officialOf(govHits[0].name);
    const city = hits.find(h => h.name !== govHits[0].name && h.govs.includes(gov));
    return { governorate: gov, city: city ? denormalize(city.name, gov) : "", ambiguous: false };
  }
  // اسمَي محافظتين في عنوان بلا «محافظة» تحسم = التباس (أحدهما غالبًا اسم شارع).
  if (govHits.length > 1) return { governorate: "", city: "", ambiguous: true };

  // كل التطابقات لازم تأدّي لمحافظة واحدة — وإلا فاضي.
  const candidates = new Set<string>();
  for (const h of hits) for (const g of h.govs) candidates.add(g);
  if (candidates.size !== 1) return { governorate: "", city: "", ambiguous: true };

  const gov = [...candidates][0];
  const official = officialOf(gov) || gov;
  return { governorate: official, city: denormalize(hits[0].name, official), ambiguous: false };
}

/** يرجّع الاسم بصيغته الأصلية من القايمة (بالهمزات) بدل المطبّع. */
function denormalize(normalized: string, gov: string): string {
  for (const c of CITIES[gov] ?? []) if (normalizeAr(c) === normalized) return c;
  return normalized;
}
