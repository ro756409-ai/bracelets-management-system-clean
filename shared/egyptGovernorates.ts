/**
 * محافظات مصر ومدنها/مراكزها — لاستخراج المحافظة من عنوان مكتوب بحرية.
 *
 * العميل بيكتب «المنصورة الصفيح امام صيدلية ياسين» — المحافظة (الدقهلية) مش مذكورة
 * أصلاً، والمدينة هي الدليل الوحيد. أخذ أول كلمة كان بيدّي «المنصورة» كمحافظة، وده
 * **غلط مضمون**: القايمة مافيهاش محافظة بالاسم ده فالـselect بيفضل فاضي، والأسوأ إنه
 * ممكن يعدّي كقيمة غلط في التصدير.
 *
 * القاعدة هنا: **يقين أو فراغ**. اسم مدينة بيأدّي لأكتر من محافظة (زي «المطرية» —
 * القاهرة والدقهلية) بيتحسب **ملتبسًا** ومابيملّيش أي حاجة، إلا لو اسم المحافظة نفسه
 * مذكور في النص. مفيش تخمين ولا «أقرب نتيجة».
 *
 * الملف في `shared/` عن قصد: الواجهة والسيرفر لازم يستخدموا نفس القايمة، ومفيش أي
 * اعتماد على قاعدة بيانات — فالقواعد دي بتتختبر من غير سيرفر. التطبيع مكرر هنا
 * (نسخة مصغّرة من `normalizeArabic`) عشان `shared/` مايعتمدش على `server/`.
 */

/** تطبيع عربي للمقارنة: صور الألف والتاء المربوطة والياء والتشكيل والأرقام الهندية. */
export function normalizeAr(text: string): string {
  return String(text ?? "")
    .replace(/[ً-ْٰ]/g, "")
    .replace(/ـ/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[ؤئ]/g, "ي")
    .replace(/[٠-٩]/g, d => String(d.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/g, d => String(d.charCodeAt(0) - 0x06f0))
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

