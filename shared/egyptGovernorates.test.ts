import { describe, it, expect } from "vitest";
import { resolveGovernorate, GOVERNORATES, CITIES } from "./egyptGovernorates";

/**
 * استخراج المحافظة من عنوان حر — **يقين أو فراغ**.
 * الحادثة: أخذ أول كلمة من العنوان («المنصورة الصفيح امام صيدلية ياسين» → «المنصورة»)
 * كان بيدّي قيمة مش موجودة في قايمة المحافظات أصلًا.
 */

const gov = (s: string) => resolveGovernorate(s).governorate;

describe("🔑 مدينة معروفة → محافظتها", () => {
  it("🔑 المنصورة → الدقهلية (الحالة الحقيقية من Production)", () => {
    expect(gov("المنصورة الصفيح امام صيدلية ياسين")).toBe("الدقهلية");
  });
  it("🔑 إدفو → أسوان", () => expect(gov("إدفو شارع المحطة")).toBe("أسوان"));
  it("🔑 إدفو بألف عادية كمان", () => expect(gov("ادفو")).toBe("أسوان"));
  it("🔑 مدينة نصر → القاهرة", () =>
    expect(gov("مدينة نصر شارع مصطفى النحاس")).toBe("القاهرة"));
  it("🔑 6 أكتوبر → الجيزة", () => expect(gov("6 أكتوبر الحي المتميز")).toBe("الجيزة"));
  it("🔑 «أكتوبر» لوحدها → الجيزة", () => expect(gov("اكتوبر")).toBe("الجيزة"));
  it("🔑 ٦ أكتوبر بأرقام عربية", () => expect(gov("٦ اكتوبر")).toBe("الجيزة"));
  it("🔑 طنطا → الغربية", () => expect(gov("طنطا ميدان الساعة")).toBe("الغربية"));
  it("🔑 شرم الشيخ → جنوب سيناء", () => expect(gov("شرم الشيخ خليج نعمة")).toBe("جنوب سيناء"));
});

describe("🔑 اسم المحافظة نفسه", () => {
  it("🔑 «كفر الشيخ» محافظة ومدينة في آنٍ واحد", () => {
    expect(gov("كفر الشيخ شارع الجيش")).toBe("كفر الشيخ");
    expect(gov("محافظة كفر الشيخ")).toBe("كفر الشيخ");
  });
  it("🔒 «كفر الشيخ» مابتتقسّمش لـ«الشيخ»", () => {
    // «الشيخ زايد» (الجيزة) و«الشيخ زويد» (شمال سيناء) موجودين — الأطول بيكسب
    expect(gov("كفر الشيخ")).toBe("كفر الشيخ");
    expect(gov("الشيخ زايد")).toBe("الجيزة");
    expect(gov("الشيخ زويد")).toBe("شمال سيناء");
  });
  it("🔑 «محافظة السويس» مع تفاصيل", () => {
    expect(gov("محافظة السويس\nالموشي تعاونيات عند مسجد الحرمين")).toBe("السويس");
  });
  it("🔑 اسم المحافظة بيحسم لو المدينة ملتبسة", () => {
    // «المطرية» موجودة في القاهرة والدقهلية — ذكر المحافظة بيحسم
    expect(gov("الدقهلية المطرية")).toBe("الدقهلية");
    expect(gov("القاهرة المطرية")).toBe("القاهرة");
  });
  it("🔑 كل المحافظات الـ27 بتتعرّف على نفسها", () => {
    for (const g of GOVERNORATES) expect(gov(g)).toBe(g);
  });
});

describe("🔒 غير المؤكد يفضل فاضي — بلا تخمين", () => {
  it("🔒 عنوان غير معروف → فاضي", () => {
    expect(gov("شارع 15 عمارة 7 الدور التالت")).toBe("");
  });
  it("🔒 نص فاضي → فاضي", () => {
    expect(gov("")).toBe("");
    expect(gov("   ")).toBe("");
  });
  it("🔒 **ممنوع أول كلمة**: «الصفيح» مش محافظة", () => {
    const r = resolveGovernorate("الصفيح امام صيدلية ياسين");
    expect(r.governorate).toBe("");
  });
  it("🔒 مدينة ملتبسة بين محافظتين → فاضي + ambiguous", () => {
    // «المطرية» في القاهرة والدقهلية، وبلا ذكر المحافظة
    const r = resolveGovernorate("المطرية شارع الترعة");
    expect(r.governorate).toBe("");
    expect(r.ambiguous).toBe(true);
  });
  it("🔒 مدينتان من محافظتين مختلفتين → فاضي", () => {
    const r = resolveGovernorate("طنطا ثم المنصورة");
    expect(r.governorate).toBe("");
    expect(r.ambiguous).toBe(true);
  });
  it("🔒 «محافظة X» غير معروفة → فاضي مش X", () => {
    expect(gov("محافظة بلد الواق واق")).toBe("");
  });
  it("🔒 جزء من كلمة مايتطابقش", () => {
    // «قنا» محافظة، بس «القناطر» مش المفروض تتطابق معاها
    expect(gov("القناطر الخيرية")).toBe("القليوبية");
  });
});

describe("🔑 المدينة منفصلة عن المحافظة", () => {
  it("🔑 المنصورة بترجع كمدينة والدقهلية كمحافظة", () => {
    const r = resolveGovernorate("المنصورة الصفيح");
    expect(r.governorate).toBe("الدقهلية");
    expect(r.city).toBe("المنصورة");
  });
  it("🔑 محافظة مذكورة ومعاها مدينتها", () => {
    const r = resolveGovernorate("الدقهلية ميت غمر");
    expect(r.governorate).toBe("الدقهلية");
    expect(r.city).toBe("ميت غمر");
  });
  it("🔑 محافظة بلا مدينة → المدينة فاضية", () => {
    expect(resolveGovernorate("محافظة قنا").city).toBe("");
  });
});

describe("🔑 سلامة الجدول", () => {
  it("🔑 كل مفاتيح المدن محافظات معروفة", () => {
    for (const k of Object.keys(CITIES)) expect(GOVERNORATES).toContain(k as any);
  });
  it("🔑 27 محافظة", () => expect(GOVERNORATES).toHaveLength(27));
});

describe("🔒 «محافظة X» الصريحة تكسب اسم شارع فيه اسم محافظة", () => {
  it("🔒 «محافظة السويس» + شارع فيه «البحر الاحمر» → السويس", () => {
    expect(
      gov("محافظة السويس\nالموشي تعاونيات البحر الاحمر عند مسجد الحرمين")
    ).toBe("السويس");
  });
  it("🔒 اسمَي محافظتين بلا «محافظة» تحسم → فاضي", () => {
    const r = resolveGovernorate("الموشي تعاونيات البحر الاحمر السويس");
    expect(r.governorate).toBe("");
    expect(r.ambiguous).toBe(true);
  });
  it("🔑 «محافظة الدقهلية» مع مدينتها", () => {
    const r = resolveGovernorate("محافظة الدقهلية ميت غمر شارع البحر");
    expect(r.governorate).toBe("الدقهلية");
    expect(r.city).toBe("ميت غمر");
  });
});
